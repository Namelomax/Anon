/**
 * Лимиты размера, общие для клиента и серверного роута.
 *
 * Вынесено в отдельный модуль СПЕЦИАЛЬНО без импортов node:http — иначе
 * клиентский бандл потянет за собой серверный код из api/_shared.ts.
 *
 * Откуда числа: serverless-функция на Vercel не принимает тело запроса больше
 * ~4.5 МБ и не отдаёт ответ больше того же объёма. Причём срабатывает это ДО
 * вызова функции: платформа отвечает 413 с текстом «Request Entity Too Large»,
 * который не является JSON — и `res.json()` на клиенте падал с
 * «Unexpected token 'R'» вместо внятного сообщения.
 *
 * Берём порог с запасом: файл едет на бэкенд в base64, а он раздувает объём
 * примерно на треть, плюс сверху идут границы multipart и поле stages.
 */
export const PLATFORM_BODY_LIMIT_BYTES = 4.5 * 1024 * 1024;

/** Потолок для ИСХОДНОГО файла с учётом раздувания base64 (×4/3) и служебных полей. */
export const MAX_UPLOAD_BYTES = 3 * 1024 * 1024;

export function formatBytes(n: number): string {
  if (n < 1024) return `${n} Б`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(0)} КБ`;
  return `${(n / 1024 / 1024).toFixed(1)} МБ`;
}

/** Понятное объяснение вместо сырого HTTP-кода. */
export function explainUploadLimit(size: number): string {
  return (
    `Файл весит ${formatBytes(size)}, а через веб-форму проходит не больше ` +
    `${formatBytes(MAX_UPLOAD_BYTES)}: платформа ограничивает размер запроса, ` +
    `а файл передаётся в base64 и становится на треть тяжелее. ` +
    `Уменьшите документ (сохраните .docx без картинок или разбейте на части) ` +
    `либо обратитесь к бэкенду напрямую — у него такого лимита нет.`
  );
}
