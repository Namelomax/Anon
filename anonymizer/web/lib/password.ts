// Правило сложности пароля — требование угрозы У-12 («подбор пароля», см.
// anonymizer/ЮРИДИЧЕСКИЕ_ДОКУМЕНТЫ/10_Авторизация_и_биллинг_правовая_фиксация.md,
// раздел 4). Минимум: длина >= 10 символов И как минимум два разных класса
// символов (строчные/заглавные буквы/цифры/спецсимволы) — это не строгий
// NIST-чеклист, а простая эвристика, отсекающая самые слабые пароли
// («1234567890», «password») без фрустрирующих пользователя составных
// требований («обязательно спецсимвол» и т.п.).
const MIN_LENGTH = 10;

const CHAR_CLASSES: RegExp[] = [
  /[a-zа-яё]/i, // буквы (латиница + кириллица одним классом — регистр значения не имеет)
  /[0-9]/, // цифры
  /[^a-zа-яё0-9]/i, // всё остальное (пробелы, пунктуация, спецсимволы)
];

/**
 * Возвращает null, если пароль достаточно сложен, иначе — русский текст
 * ошибки для показа пользователю.
 */
export function validatePasswordStrength(password: string): string | null {
  if (password.length < MIN_LENGTH) {
    return `Пароль должен быть не короче ${MIN_LENGTH} символов.`;
  }
  const classesPresent = CHAR_CLASSES.filter((re) => re.test(password)).length;
  if (classesPresent < 2) {
    return "Пароль должен содержать хотя бы два разных типа символов (буквы, цифры, спецсимволы).";
  }
  return null;
}

// Простая проверка формата email — не претендует на полное соответствие
// RFC 5322 (это невозможно без ложных срабатываний), отсекает только явный
// мусор («не является адресом эл. почты вообще»). Финальная валидация
// адреса — уникальность в БД (User.email @unique) и, при необходимости,
// письмо-подтверждение (вне текущего объёма задачи).
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

export function isValidEmail(email: string): boolean {
  return EMAIL_RE.test(email);
}
